#!/usr/bin/env python3
"""Regenerate the showcase fonts: Inter (SIL OFL 1.1) with Lucide icons (ISC) merged in.

    npm install lv_font_conv lucide-static
    python3 generate.py --inter /path/to/inter/otf --node-modules ./node_modules

Writes gv_font_*.c and gv_icons.h next to this script. Each font holds Latin text plus the icons
the showcase uses, so a label can mix the two ("\\uE178 Sunny"). 4 bits per pixel, uncompressed.
Glyphs a font lacks, such as the LV_SYMBOL_* icons LVGL widgets draw, fall back to Montserrat 14.
"""
import argparse
import json
import os
import subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
TEXT = "0x20-0x7E,0xA0,0xB0,0xB7,0x2013,0x2019,0x2022,0x2212"
DIGITS = "0x20,0x25,0x2B-0x3A,0x43,0x46,0xB0"  # digits, : . - + % degrees, C and F
ICONS = [
    "sun", "cloud-sun", "cloud", "cloud-rain", "moon", "sunrise", "sunset", "wind", "droplets",
    "thermometer", "umbrella", "lightbulb", "lamp-floor", "lamp-ceiling", "blinds", "tv", "speaker",
    "fan", "air-vent", "power", "sofa", "bed", "clapperboard", "house", "wifi", "bluetooth", "monitor",
    "sun-medium", "volume-1", "volume-2", "bell", "battery-medium", "battery-full", "battery-charging",
    "info", "play", "pause", "skip-back", "skip-forward", "shuffle", "repeat", "search", "music",
    "heart", "footprints", "zap", "plug", "chevron-down", "chevron-right", "chevron-left", "minus",
    "plus", "map-pin", "navigation", "gauge", "settings", "flame", "snowflake", "disc-3", "radio",
    "list-music", "library", "smartphone", "sliders-horizontal", "layout-grid", "clock", "calendar",
    "activity", "heart-pulse", "leaf", "sparkles", "lock", "user", "ellipsis", "airplay",
    "arrow-up-right", "arrow-down-right", "sun-dim", "keyboard", "image", "mic", "timer", "check",
]
# name, Inter file, size, text range, with icons
FONTS = [
    ("gv_font_12", "Inter-Medium.otf", 12, TEXT, True),
    ("gv_font_14", "Inter-Medium.otf", 14, TEXT, True),
    ("gv_font_16", "Inter-Medium.otf", 16, TEXT, True),
    ("gv_font_16b", "Inter-SemiBold.otf", 16, TEXT, True),
    ("gv_font_20", "Inter-SemiBold.otf", 20, TEXT, True),
    ("gv_font_24", "InterDisplay-SemiBold.otf", 24, TEXT, True),
    ("gv_font_32", "InterDisplay-SemiBold.otf", 32, TEXT, True),
    ("gv_font_48", "InterDisplay-Light.otf", 48, DIGITS, True),
    ("gv_font_72", "InterDisplay-Thin.otf", 72, DIGITS, False),
]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--inter", required=True, help="directory with the Inter and InterDisplay .otf files")
    ap.add_argument("--node-modules", default="node_modules")
    a = ap.parse_args()
    nm = os.path.abspath(a.node_modules)
    conv = os.path.join(nm, ".bin", "lv_font_conv")
    lucide = os.path.join(nm, "lucide-static", "font", "lucide.ttf")
    cps = json.load(open(os.path.join(nm, "lucide-static", "font", "codepoints.json")))
    missing = [n for n in ICONS if n not in cps]
    if missing:
        raise SystemExit("Lucide has no icon named " + ", ".join(missing))
    icon_range = ",".join(hex(cps[n]) for n in ICONS)

    for name, otf, size, rng, icons in FONTS:
        cmd = [conv, "--bpp", "4", "--size", str(size), "--no-compress", "--format", "lvgl",
               "--lv-include", "lvgl.h", "--lv-font-name", name, "--lv-fallback", "lv_font_montserrat_14", "-o", os.path.join(HERE, name + ".c"),
               "--font", os.path.join(a.inter, otf), "-r", rng]
        if icons:
            cmd += ["--font", lucide, "-r", icon_range]
        subprocess.run(cmd, check=True)
        # keep the build machine's paths out of the generated header comment
        out = os.path.join(HERE, name + ".c")
        src = open(out).read()
        for path, short in ((HERE + os.sep, ""), (os.path.abspath(a.inter) + os.sep, ""), (os.path.dirname(lucide) + os.sep, "")):
            src = src.replace(path, short)
        open(out, "w").write(src)

    with open(os.path.join(HERE, "gv_icons.h"), "w") as h:
        h.write("/* Generated by generate.py. Lucide icons (ISC licence) as UTF-8 strings for the gv_font_* fonts. */\n")
        h.write("#ifndef GV_ICONS_H\n#define GV_ICONS_H\n\n")
        for n in ICONS:
            b = chr(cps[n]).encode("utf-8")
            h.write("#define GV_IC_%s \"%s\"\n" % (n.upper().replace("-", "_"), "".join("\\x%02X" % c for c in b)))
        h.write("\n#endif\n")
        h.write("")
    with open(os.path.join(HERE, "gv_fonts.h"), "w") as h:
        h.write("/* Generated by generate.py. Inter (SIL OFL 1.1) with Lucide icons (ISC). */\n")
        h.write("#ifndef GV_FONTS_H\n#define GV_FONTS_H\n\n#include \"lvgl.h\"\n\n")
        for f in FONTS:
            h.write("LV_FONT_DECLARE(%s)\n" % f[0])
        h.write("\n#endif\n")


if __name__ == "__main__":
    main()
